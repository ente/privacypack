// Not Radix's focus guards, which only redirect focus.
const TABBABLE =
    "a[href], button:not([disabled]), input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([data-radix-focus-guard])";

/**
 * Radix keeps Tab inside a menu. As in the ARIA menu button pattern, leave
 * it instead, as if the menu sat just after its trigger: Shift+Tab goes to
 * the trigger and Tab to the control after it. Focus moving out closes a
 * non-modal menu, and Radix then leaves focus where it is.
 */
function tabOutOfMenu(event: React.KeyboardEvent<HTMLDivElement>) {
    if (event.key !== "Tab" || event.altKey || event.ctrlKey || event.metaKey) {
        return;
    }
    const menu = event.currentTarget;
    const trigger = document.getElementById(
        menu.getAttribute("aria-labelledby") ?? "",
    );
    if (!trigger) return;
    event.preventDefault();
    const next = event.shiftKey
        ? undefined
        : Array.from(document.querySelectorAll<HTMLElement>(TABBABLE)).find(
              (element) =>
                  trigger.compareDocumentPosition(element) &
                      Node.DOCUMENT_POSITION_FOLLOWING &&
                  !trigger.contains(element) &&
                  // Another menu can still be animating closed. Its items
                  // disappear when it unmounts, taking focus with them.
                  !element.closest("[data-radix-menu-content]") &&
                  element.tabIndex >= 0 &&
                  element.getClientRects().length > 0,
          );
    // With nothing after the trigger, Tab also closes the menu on it.
    (next ?? trigger).focus();
}

function DropdownMenuContent({
    className,
    sideOffset = 4,
    onKeyDown,
    ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content>) {
    return (
        <DropdownMenuPrimitive.Portal>
            <DropdownMenuPrimitive.Content
                data-slot="dropdown-menu-content"
                sideOffset={sideOffset}
                onKeyDown={(event) => {
                    onKeyDown?.(event);
                    if (!event.defaultPrevented) tabOutOfMenu(event);
                }}
                className={cn(
                    // Portalled to <body>, outside the page font's wrapper
                    // (app/layout.tsx).
                    "font-(family-name:--font-jetbrains-mono)",
                    // No open or close animation for reduced motion, so a
                    // closing menu unmounts at once. data-[state] matches the
                    // specificity of the data-[state=...] animations below,
                    // which Tailwind emits before it.
                    "motion-reduce:data-[state]:animate-none",
                    "bg-popover text-popover-foreground data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 z-50 max-h-(--radix-dropdown-menu-content-available-height) max-w-(--radix-dropdown-menu-content-available-width) min-w-[8rem] origin-(--radix-dropdown-menu-content-transform-origin) overflow-x-hidden overflow-y-auto border p-1 shadow-md",
                    className,
                )}
                {...props}
            />
        </DropdownMenuPrimitive.Portal>
    );
}

